// Ready-to-paste GitHub Pull Request description for a verified resurrection.
// Deterministic: no timestamps, no randomness. The same input always yields the same Markdown.
import { describeTypecheck } from "../crew/ts-verifier.js";
import { plural } from "../text/plural.js";
import { diffLines, type DiffLine } from "../web/line-diff.js";
import { describeMutation, generateCertificate, type CertificateInput } from "./certificate.js";

export interface PrSummaryInput extends CertificateInput {
  /** Specimen / function name shown in the title. */
  readonly name: string;
  /** Lines of unchanged context around each change in the diff snippet (default 1). */
  readonly contextLines?: number;
  /** Maximum lines in the diff snippet (default 40). */
  readonly maxDiffLines?: number;
}

/** Lazarus' own header comments on generated code (`// Resurrected by ...`, `// ast-rules: ...`): not part of the change. */
const GENERATED_HEADER = /^\/\/ (Resurrected by Lazarus|ast-rules:|ast-speculative:|ast-refine:)/;

export function stripGeneratedHeader(code: string): string {
  const lines = code.replace(/\r\n?/g, "\n").split("\n");
  let i = 0;
  while (i < lines.length && GENERATED_HEADER.test(lines[i] ?? "")) i++;
  return lines.slice(i).join("\n").trim();
}

/** Changed lines with `context` lines around them, as unified-diff text, capped at `max` lines. */
export function compactDiff(oldText: string, newText: string, context = 1, max = 40): { text: string; added: number; removed: number; truncated: number } {
  const lines = diffLines(oldText, newText);
  const keep = lines.map(() => false);
  lines.forEach((l, i) => {
    if (l.kind === "same") return;
    for (let k = Math.max(0, i - context); k <= Math.min(lines.length - 1, i + context); k++) keep[k] = true;
  });
  const out: string[] = [];
  let skipping = false;
  lines.forEach((l: DiffLine, i) => {
    if (!keep[i]) {
      if (!skipping && out.length > 0) out.push("@@");
      skipping = true;
      return;
    }
    skipping = false;
    out.push(`${l.kind === "del" ? "-" : l.kind === "add" ? "+" : " "}${l.text}`);
  });
  while (out.at(-1) === "@@") out.pop();
  const truncated = Math.max(0, out.length - max);
  return {
    text: out.slice(0, max).join("\n"),
    added: lines.filter((l) => l.kind === "add").length,
    removed: lines.filter((l) => l.kind === "del").length,
    truncated,
  };
}

export function buildGitHubPrSummary(input: PrSummaryInput): string {
  const cert = generateCertificate(input);
  const legacy = input.legacySource.replace(/\r\n?/g, "\n").trim();
  const modern = stripGeneratedHeader(input.modernCode);
  const diff = compactDiff(legacy, modern, input.contextLines ?? 1, input.maxDiffLines ?? 40);
  const parity = cert.parity;
  const proof = [
    `- **Behavioral parity:** exact \`Object.is\` across ${plural(parity.runs, "differential fuzz run")}${parity.boundaryRuns > 0 ? ` (${parity.boundaryRuns} from the boundary corpus)` : ""}, ${parity.mode === "exact Object.is (tagged)" ? "tagged so -0, NaN and undefined are compared exactly" : "JSON-level comparison"}.`,
    `- **Self-healing:** ${parity.selfHealed ? `healed in ${plural(parity.attempts, "attempt")}` : "first draft held"}${cert.rolledBack.length > 0 ? `; rolled back ${cert.rolledBack.map((r) => `\`${r}\``).join(", ")}` : ""}.`,
    `- **TypeScript:** ${cert.typecheck !== undefined ? `\`${describeTypecheck(cert.typecheck)}\`` : "not checked"}.`,
    ...(cert.mutation !== undefined ? [`- **Mutation audit:** ${describeMutation(cert.mutation)}.`] : []),
    `- **Legacy debt score:** ${cert.debtScore}/100 (${cert.debtGrade}).`,
  ];
  return [
    `## Resurrect \`${input.name}\` with Lazarus`,
    ``,
    `Modernizes a legacy ES5 / CommonJS specimen to ES2022 / TypeScript with proven behavioral parity.`,
    ``,
    `**Provenance:** ${cert.provenanceLine}  `,
    `**Legacy SHA-256:** \`${cert.sha256}\` (certificate \`${cert.id}\`)`,
    ``,
    `### Proof`,
    ...proof,
    ``,
    `### Modernized`,
    ...(cert.modernized.length > 0 ? cert.modernized.map((m) => `- ${m}`) : ["- Nothing needed rewriting."]),
    ``,
    `### Diff (legacy -> resurrected, ${plural(diff.removed, "line")} removed, ${plural(diff.added, "line")} added)`,
    "```diff",
    diff.text,
    ...(diff.truncated > 0 ? [`@@ ${plural(diff.truncated, "more line")}: see resurrection.patch`] : []),
    "```",
    ``,
    `_Generated by Lazarus. Parity is proven over the fuzzed input domain by differential fuzzing in an isolated sandbox._`,
    ``,
  ].join("\n");
}
